    private I18n() {}

    /**
     * Resolves a translated UI string for the currently set active language.
     * If not found, falls back safely to English.
     */
    public static String get(String key, String langCode) {
        if (langCode != null) {
            String base = langCode.contains("-") ? langCode.substring(0, langCode.indexOf('-')) : langCode;
            base = base.toLowerCase(Locale.ROOT);
            Map<String, String> langMap = TRANSLATIONS.get(base);
            if (langMap != null && langMap.containsKey(key)) {
                String val = langMap.get(key);
                return val != null ? val.replace("\\n", "\n") : key;
            }
        }
        Map<String, String> en = TRANSLATIONS.get("en");
        if (en != null && en.containsKey(key)) {
            String val = en.get(key);
            return val != null ? val.replace("\\n", "\n") : key;
        }
        return key;
    }

    /**
     * Resolves a translated UI string formatted with arguments using the target locale.
     */
    public static String format(String key, String langCode, Object... args) {
        String pattern = get(key, langCode);
        try {
            Locale locale = (langCode != null && !langCode.isEmpty())
                ? (langCode.contains("-") ? new Locale(langCode.substring(0, langCode.indexOf('-'))) : new Locale(langCode))
                : Locale.getDefault();
            return String.format(locale, pattern, args);
        } catch (Exception e) {
            return String.format(pattern, args);
        }
    }

    /**
     * Updates Android runtime Context Resources, default Locale, and fontScale.
     */
    public static void applyLocale(Context context, String languageCode, String regionCode) {
        applyLocaleAndScale(context, languageCode, regionCode, 1.0f);
    }

    public static void applyLocaleAndScale(Context context, String languageCode, String regionCode, float fontScale) {
        if (languageCode == null || languageCode.isEmpty()) languageCode = "en";
        if (regionCode == null) regionCode = "";

        Locale targetLocale;
        if (!regionCode.isEmpty()) {
            targetLocale = new Locale(languageCode, regionCode);
        } else {
            targetLocale = new Locale(languageCode);
        }

        Locale.setDefault(targetLocale);
        if (context != null) {
            Resources res = context.getResources();
            Configuration config = new Configuration(res.getConfiguration());
            config.setLocale(targetLocale);
            if (fontScale > 0.1f) {
                config.fontScale = fontScale;
            }
            res.updateConfiguration(config, res.getDisplayMetrics());
        }
    }
